from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional
from datetime import datetime


@dataclass
class AgentState:
    """
    Central authoritative state for the agentic evaluation workflow.

    Important design rule:
    ----------------------
    The state tracks both:
      1. What has already been done.
      2. What the user actually asked the agent to accomplish.

    This prevents a narrow request such as:
        "Inspect my model and dataset"

    from accidentally becoming:
        inspect -> evaluate -> quality -> robustness -> transform -> report
    """

    # ------------------------------------------------------------------
    # Project / request information
    # ------------------------------------------------------------------

    project_id: str
    user_goal: str

    # Requested workflow / intent.
    #
    # Examples:
    #   inspection
    #   baseline_metrics
    #   full_evaluation
    #   improve_dataset
    #   targeted_transform
    #   report
    #   contextual
    #   comparison
    #
    # This is intentionally separate from user_goal.
    requested_workflow: str = "full_evaluation"

    # Optional human-readable objective generated by the router.
    workflow_objective: Optional[str] = None

    # ------------------------------------------------------------------
    # Model / dataset
    # ------------------------------------------------------------------

    model_id: Optional[str] = None
    model_path: Optional[str] = None

    dataset_id: Optional[str] = None
    dataset_path: Optional[str] = None

    current_dataset_version: Optional[str] = None
    evaluated_dataset_version: Optional[str] = None

    target_column: Optional[str] = None
    task_type: Optional[str] = None

    # ------------------------------------------------------------------
    # Inspection / validation flags
    # ------------------------------------------------------------------

    model_inspected: bool = False
    dataset_inspected: bool = False
    compatibility_validated: bool = False

    # ------------------------------------------------------------------
    # Evaluation flags
    # ------------------------------------------------------------------

    baseline_evaluated: bool = False
    data_quality_evaluated: bool = False
    robustness_evaluated: bool = False

    # ------------------------------------------------------------------
    # Results
    # ------------------------------------------------------------------

    model_metadata: Dict[str, Any] = field(default_factory=dict)
    dataset_metadata: Dict[str, Any] = field(default_factory=dict)

    baseline_metrics: Dict[str, Any] = field(default_factory=dict)
    data_quality: Dict[str, Any] = field(default_factory=dict)
    robustness_results: Dict[str, Any] = field(default_factory=dict)

    latest_metrics: Dict[str, Any] = field(default_factory=dict)

    # ------------------------------------------------------------------
    # Transformation / experiment information
    # ------------------------------------------------------------------

    transformations_applied: List[Dict[str, Any]] = field(default_factory=list)

    experiments: List[Dict[str, Any]] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Agent history
    # ------------------------------------------------------------------

    observations: List[Dict[str, Any]] = field(default_factory=list)
    actions_taken: List[Dict[str, Any]] = field(default_factory=list)

    messages_history: List[Dict[str, Any]] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Runtime
    # ------------------------------------------------------------------

    iteration: int = 0
    max_iterations: int = 20

    status: str = "initialized"

    stop_reason: Optional[str] = None

    created_at: str = field(
        default_factory=lambda: datetime.utcnow().isoformat()
    )

    updated_at: str = field(
        default_factory=lambda: datetime.utcnow().isoformat()
    )

    # ------------------------------------------------------------------
    # Workflow helpers
    # ------------------------------------------------------------------

    def update_timestamp(self) -> None:
        self.updated_at = datetime.utcnow().isoformat()

    def is_complete(self) -> bool:
        """
        Global terminal-state check.

        NOTE:
        This does NOT determine whether the user's requested workflow
        is finished.

        Workflow-specific completion is handled by workflow_complete().
        """

        if self.status in {
            "completed",
            "failed",
            "waiting_for_approval",
        }:
            return True

        if self.iteration >= self.max_iterations:
            return True

        return False

    # ------------------------------------------------------------------
    # Workflow-specific completion
    # ------------------------------------------------------------------

    def workflow_complete(self) -> bool:
        """
        Determine whether the currently requested workflow has achieved
        its objective.

        This is the key mechanism that prevents narrow requests from
        falling through into the complete evaluation pipeline.
        """

        workflow = (self.requested_workflow or "").lower().strip()

        # --------------------------------------------------------------
        # Inspection only
        # --------------------------------------------------------------

        if workflow in {
            "inspection",
            "inspect",
            "inspect_model_dataset",
        }:
            return (
                self.model_inspected
                and self.dataset_inspected
                and self.compatibility_validated
            )

        # --------------------------------------------------------------
        # Baseline metrics only
        # --------------------------------------------------------------

        if workflow in {
            "baseline",
            "baseline_metrics",
            "baseline_evaluation",
        }:
            return self.baseline_evaluated

        # --------------------------------------------------------------
        # Full evaluation
        # --------------------------------------------------------------

        if workflow in {
            "full_evaluation",
            "evaluate",
            "evaluation",
        }:
            return self.full_evaluation_complete()

        # --------------------------------------------------------------
        # Dataset improvement
        # --------------------------------------------------------------

        if workflow in {
            "improve_dataset",
            "dataset_improvement",
            "improvement",
        }:
            return self.improvement_complete()

        # --------------------------------------------------------------
        # Targeted transformation
        # --------------------------------------------------------------

        if workflow in {
            "targeted_transform",
            "transform",
            "transformation",
            "clean_dataset",
            "balance_dataset",
            "handle_outliers",
            "scale_dataset",
            "add_noise",
        }:
            return len(self.transformations_applied) > 0

        # --------------------------------------------------------------
        # Report
        # --------------------------------------------------------------

        if workflow in {
            "report",
            "generate_report",
        }:
            return self.status == "completed"

        # --------------------------------------------------------------
        # Contextual / comparison
        # --------------------------------------------------------------

        if workflow in {
            "contextual",
            "comparison",
        }:
            return self.status == "completed"

        # Unknown workflow:
        # Do not silently execute the entire pipeline.
        return False

    def full_evaluation_complete(self) -> bool:
        """
        Full evaluation requires the complete diagnostic cycle.

        Transformations are optional because a healthy dataset may not
        need them.
        """

        return (
            self.model_inspected
            and self.dataset_inspected
            and self.compatibility_validated
            and self.baseline_evaluated
            and self.data_quality_evaluated
            and self.robustness_evaluated
            and (
                self.evaluated_dataset_version
                == self.current_dataset_version
            )
        )

    def improvement_complete(self) -> bool:
        """
        Dataset improvement is complete only after:

          1. At least one transformation was applied.
          2. The transformed version was evaluated.
          3. The current version has current metrics.

        This deliberately does not require report generation.
        """

        return (
            len(self.transformations_applied) > 0
            and bool(self.latest_metrics)
            and (
                self.evaluated_dataset_version
                == self.current_dataset_version
            )
        )

    # ------------------------------------------------------------------
    # Human-readable workflow information
    # ------------------------------------------------------------------

    def get_workflow_context(self) -> Dict[str, Any]:
        """
        Small context object used by the planner.
        """

        return {
            "requested_workflow": self.requested_workflow,
            "workflow_objective": self.workflow_objective,
            "workflow_complete": self.workflow_complete(),
            "model_inspected": self.model_inspected,
            "dataset_inspected": self.dataset_inspected,
            "compatibility_validated": self.compatibility_validated,
            "baseline_evaluated": self.baseline_evaluated,
            "data_quality_evaluated": self.data_quality_evaluated,
            "robustness_evaluated": self.robustness_evaluated,
            "current_dataset_version": self.current_dataset_version,
            "evaluated_dataset_version": self.evaluated_dataset_version,
            "transformations_count": len(self.transformations_applied),
            "experiments_count": len(self.experiments),
        }

    # ------------------------------------------------------------------
    # Summary context for LLM
    # ------------------------------------------------------------------

    def get_summary_context(self) -> Dict[str, Any]:
        """
        Return a compact authoritative representation of the current
        state.

        The LLM may use this for reasoning, but Python remains the
        authority for actual metrics and workflow legality.
        """

        return {
            "project_id": self.project_id,
            "user_goal": self.user_goal,

            "requested_workflow": self.requested_workflow,
            "workflow_objective": self.workflow_objective,
            "workflow_complete": self.workflow_complete(),

            "model_id": self.model_id,
            "dataset_id": self.dataset_id,

            "current_dataset_version": self.current_dataset_version,
            "evaluated_dataset_version": self.evaluated_dataset_version,

            "target_column": self.target_column,
            "task_type": self.task_type,

            "model_inspected": self.model_inspected,
            "dataset_inspected": self.dataset_inspected,
            "compatibility_validated": self.compatibility_validated,

            "baseline_evaluated": self.baseline_evaluated,
            "data_quality_evaluated": self.data_quality_evaluated,
            "robustness_evaluated": self.robustness_evaluated,

            "model_metadata": self.model_metadata,
            "dataset_metadata": self.dataset_metadata,

            "baseline_metrics": self.baseline_metrics,
            "data_quality": self.data_quality,
            "robustness_results": self.robustness_results,
            "latest_metrics": self.latest_metrics,

            "transformations_applied": self.transformations_applied,
            "experiments": self.experiments,

            "iteration": self.iteration,
            "status": self.status,
            "stop_reason": self.stop_reason,
        }

    # ------------------------------------------------------------------
    # History helpers
    # ------------------------------------------------------------------

    def add_observation(
        self,
        action: str,
        result: Any,
    ) -> None:
        self.observations.append(
            {
                "timestamp": datetime.utcnow().isoformat(),
                "action": action,
                "result": result,
            }
        )
        self.update_timestamp()

    def add_action(
        self,
        action: str,
        arguments: Optional[Dict[str, Any]] = None,
    ) -> None:
        self.actions_taken.append(
            {
                "timestamp": datetime.utcnow().isoformat(),
                "action": action,
                "arguments": arguments or {},
            }
        )
        self.update_timestamp()

    def add_message(
        self,
        role: str,
        content: str,
    ) -> None:
        self.messages_history.append(
            {
                "timestamp": datetime.utcnow().isoformat(),
                "role": role,
                "content": content,
            }
        )
        self.update_timestamp()

    # ------------------------------------------------------------------
    # Dataset version safety
    # ------------------------------------------------------------------

    def mark_dataset_changed(
        self,
        new_version: str,
    ) -> None:
        """
        Mark a new immutable dataset version.

        Any metrics belonging to the previous dataset version must not
        be treated as metrics for the new version.
        """

        self.current_dataset_version = new_version

        if self.evaluated_dataset_version != new_version:
            self.latest_metrics = {}

        self.update_timestamp()

    # ------------------------------------------------------------------
    # Serialization
    # ------------------------------------------------------------------

    def to_dict(self) -> Dict[str, Any]:
        """
        Convert state to a serializable dictionary.
        """

        return {
            "project_id": self.project_id,
            "user_goal": self.user_goal,

            "requested_workflow": self.requested_workflow,
            "workflow_objective": self.workflow_objective,

            "model_id": self.model_id,
            "model_path": self.model_path,

            "dataset_id": self.dataset_id,
            "dataset_path": self.dataset_path,

            "current_dataset_version": self.current_dataset_version,
            "evaluated_dataset_version": self.evaluated_dataset_version,

            "target_column": self.target_column,
            "task_type": self.task_type,

            "model_inspected": self.model_inspected,
            "dataset_inspected": self.dataset_inspected,
            "compatibility_validated": self.compatibility_validated,

            "baseline_evaluated": self.baseline_evaluated,
            "data_quality_evaluated": self.data_quality_evaluated,
            "robustness_evaluated": self.robustness_evaluated,

            "model_metadata": self.model_metadata,
            "dataset_metadata": self.dataset_metadata,

            "baseline_metrics": self.baseline_metrics,
            "data_quality": self.data_quality,
            "robustness_results": self.robustness_results,
            "latest_metrics": self.latest_metrics,

            "transformations_applied": self.transformations_applied,
            "experiments": self.experiments,

            "observations": self.observations,
            "actions_taken": self.actions_taken,
            "messages_history": self.messages_history,

            "iteration": self.iteration,
            "max_iterations": self.max_iterations,

            "status": self.status,
            "stop_reason": self.stop_reason,

            "created_at": self.created_at,
            "updated_at": self.updated_at,
        }