from pathlib import Path
import pytest
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.datasets import make_classification
import joblib

from app.services.project_service import project_service
from app.agent.state import AgentState
from app.agent.agent import AgentRunner
from app.agent.tools import tool_registry
from app.memory.chroma_memory import project_memory
from app.core.database import db


def test_full_agentic_and_security_workflow_e2e(tmp_path):
    # 1. Generate Synthetic Model & Imbalanced Dataset (5 features + 1 target column)
    X, y = make_classification(
        n_samples=250, n_features=5, n_informative=3, n_redundant=1,
        weights=[0.85, 0.15], random_state=42
    )
    df = pd.DataFrame(X, columns=[f"f_{i}" for i in range(5)])
    df["target"] = y

    raw_csv_path = tmp_path / "imbalanced_customer_data.csv"
    df.to_csv(raw_csv_path, index=False)

    clf = RandomForestClassifier(n_estimators=15, random_state=42)
    clf.fit(X, y)

    raw_model_path = tmp_path / "classifier_model.joblib"
    joblib.dump(clf, raw_model_path)

    # 2. Create Project
    proj = project_service.create_project(name="E2E Full Security Test", description="Full E2E test")
    assert proj.id is not None

    # 3. Upload Model and Dataset
    m_info = project_service.upload_model(proj.id, str(raw_model_path), "classifier_model.joblib")
    d_info = project_service.upload_dataset(proj.id, str(raw_csv_path), "imbalanced_customer_data.csv")

    assert m_info["framework"] == "sklearn"
    assert d_info["version"] == "v001"

    # Resolve exact disk folder names generated by project_service
    dataset_id = d_info.get("id") or Path(d_info["file_path"]).parent.parent.parent.name
    model_id = m_info.get("id") or Path(m_info["file_path"]).parent.name

    # 4. Initialize Agent State
    state = AgentState(
        project_id=proj.id,
        user_goal="Evaluate my model and improve it if the dataset has problems.",
        model_id=model_id,
        model_path=m_info["file_path"],
        dataset_id=dataset_id,
        dataset_path=d_info["file_path"],
        current_dataset_version="v001",
        target_column="target"
    )

    # 5. Run Agent Closed-Loop Evaluation
    runner = AgentRunner(state)
    final_state = runner.run_until_complete()

    actions = [
        a["action"] if isinstance(a, dict) else getattr(a, "action", "")
        for a in final_state.actions_taken
    ]

    # Verify agentic execution lifecycle
    assert "inspect_model" in actions
    assert "inspect_dataset" in actions
    assert "validate_model_dataset" in actions
    assert "evaluate_performance" in actions
    assert final_state.status == "completed"

    # 6. Run Security Attack & Defense Tools
    attack_res = tool_registry.execute_tool(
        "zoo",
        {"model_path": m_info["file_path"], "dataset_path": d_info["file_path"], "target_column": "target"}
    )
    assert attack_res["status"] == "success"

    defense_res = tool_registry.execute_tool(
        "gaussian_augmentation",
        {"model_path": m_info["file_path"], "dataset_path": d_info["file_path"], "target_column": "target", "sigma": 0.5}
    )
    assert defense_res["status"] == "success"

    # 7. Persist Security Experiment Record
    save_res = tool_registry.execute_tool(
        "save_experiment",
        {
            "project_id": proj.id,
            "model_id": model_id,
            "operation": "zoo",
            "input_dataset_version": "v001",
            "output_dataset_version": "v001",
            "metrics_before": {"accuracy": 0.90},
            "metrics_after": {"accuracy": 0.65},
            "agent_reasoning": "Executed ZOO evasion attack."
        }
    )
    assert save_res["status"] == "success"

    # 8. Verify SQLite Persistence
    with db._get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT * FROM experiments WHERE project_id = ?", (proj.id,))
        exp_rows = cursor.fetchall()
        assert len(exp_rows) >= 1

    # 9. Test Memory Query (Q&A)
    query_res = project_memory.query_history(proj.id, "ZOO evasion attack", n_results=1)
    assert len(query_res) > 0